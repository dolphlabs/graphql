package main

import (
	"fmt"
	"sort"
	"strings"
)

func generate(s *schema, contextType string) (string, error) {
	if contextType == "" {
		contextType = "graphql.Context"
	}
	if err := validContextType(contextType); err != nil {
		return "", fmt.Errorf("context type is not a valid Slang type expression")
	}
	if err := validateGeneratedNames(s); err != nil {
		return "", err
	}
	var b strings.Builder
	b.WriteString("// Code generated by graphqlc. DO NOT EDIT.\n")
	b.WriteString("// Edit the SDL and regenerate; resolvers remain ordinary named functions.\n\n")
	b.WriteString("import \"graphql\" as __graphql;\nimport \"builder\";\nimport \"json\";\n\n")
	fmt.Fprintf(&b, "pub let GRAPHQL_QUERY_ROOT = %q;\n", s.queryRoot)
	if s.mutRoot != "" {
		fmt.Fprintf(&b, "pub let GRAPHQL_MUTATION_ROOT = %q;\n", s.mutRoot)
	}
	b.WriteByte('\n')
	for _, d := range s.types {
		if d.kind == "enum" {
			fmt.Fprintf(&b, "pub enum %s {\n", d.name)
			for _, name := range d.values {
				fmt.Fprintf(&b, "    %s,\n", name)
			}
			b.WriteString("}\n\n")
		}
	}
	for _, d := range s.types {
		if d.kind != "type" && d.kind != "input" {
			continue
		}
		fmt.Fprintf(&b, "pub gc struct %s {\n", d.name)
		for _, f := range d.fields {
			typ, err := s.slangType(f.typ)
			if err != nil {
				return "", fmt.Errorf("%s.%s: %w", d.name, f.name, err)
			}
			fmt.Fprintf(&b, "    %s: %s,\n", f.name, typ)
		}
		b.WriteString("}\n\n")
	}
	for _, d := range s.types {
		if d.kind != "type" {
			continue
		}
		for _, f := range d.fields {
			if len(f.args) == 0 {
				continue
			}
			fmt.Fprintf(&b, "pub gc struct %s {\n", argsTypeName(d.name, f.name))
			for _, arg := range f.args {
				typ, err := s.slangType(arg.typ)
				if err != nil {
					return "", fmt.Errorf("%s.%s(%s): %w", d.name, f.name, arg.name, err)
				}
				fmt.Fprintf(&b, "    %s: %s,\n", arg.name, typ)
			}
			b.WriteString("}\n\n")
		}
	}
	b.WriteString("// Implement one named resolver for each schema field.\n")
	b.WriteString("// Generated wrappers call them directly; no resolver registry is used.\n")
	for _, d := range s.types {
		if d.kind != "type" {
			continue
		}
		for _, f := range d.fields {
			argsType := "__graphql.NoArgs"
			if len(f.args) > 0 {
				argsType = argsTypeName(d.name, f.name)
			}
			retType, err := s.slangType(f.typ)
			if err != nil {
				return "", err
			}
			parentType := resolverParentType(s, d.name)
			fmt.Fprintf(&b, "pub fn graphql_call_%s_%s(parent: %s, args: %s, ctx: %s) -> result[%s, str] {\n",
				d.name, f.name, parentType, argsType, contextType, retType)
			fmt.Fprintf(&b, "    return %s(parent, args, ctx);\n}\n\n",
				resolverName(d.name, f.name))
		}
	}
	execution, err := generateExecution(s, contextType)
	if err != nil {
		return "", err
	}
	b.WriteString(execution)
	return strings.TrimRight(b.String(), "\n") + "\n", nil
}

func resolverParentType(s *schema, object string) string {
	if object == s.queryRoot || object == s.mutRoot {
		return "__graphql.Root"
	}
	return object
}

func validContextType(input string) error {
	if input == "" {
		return fmt.Errorf("empty type")
	}
	for i := 0; i < len(input); {
		start := i
		if !nameStart(input[i]) {
			return fmt.Errorf("expected type identifier")
		}
		i++
		for i < len(input) && nameContinue(input[i]) {
			i++
		}
		if err := validSlangIdentifier(input[start:i]); err != nil {
			return err
		}
		if i == len(input) {
			return nil
		}
		if input[i] != '.' {
			return fmt.Errorf("context type must be a named type")
		}
		i++
	}
	return fmt.Errorf("incomplete type name")
}

func (s *schema) slangType(t *typeRef) (string, error) {
	var base string
	if t.list {
		inner, err := s.slangType(t.inner)
		if err != nil {
			return "", err
		}
		base = "[" + inner + "]"
	} else {
		switch t.name {
		case "Int":
			base = "int"
		case "Float":
			base = "float"
		case "String", "ID":
			base = "str"
		case "Boolean":
			base = "bool"
		default:
			if _, ok := s.definitions[t.name]; !ok {
				return "", fmt.Errorf("unknown GraphQL type %q", t.name)
			}
			base = t.name
		}
	}
	if !t.nonNull {
		base = "opt[" + base + "]"
	}
	return base, nil
}

func validateGeneratedNames(s *schema) error {
	generated := make(map[string]string)
	add := func(name, source string) error {
		if old, ok := generated[name]; ok {
			return fmt.Errorf("generated identifier %q collides between %s and %s", name, old, source)
		}
		generated[name] = source
		return nil
	}
	if err := add("GRAPHQL_QUERY_ROOT", "generated query root constant"); err != nil {
		return err
	}
	if err := add("graphql_execute", "generated request executor"); err != nil {
		return err
	}
	if err := add("graphql_schema_has_object_type", "generated schema type validator"); err != nil {
		return err
	}
	if s.mutRoot != "" {
		if err := add("GRAPHQL_MUTATION_ROOT", "generated mutation root constant"); err != nil {
			return err
		}
	}
	for _, d := range s.types {
		if err := add(d.name, "schema type "+d.name); err != nil {
			return err
		}
		if d.kind == "type" {
			for _, generated := range []string{"graphql_validate_" + d.name, "graphql_emit_" + d.name} {
				if err := add(generated, "generated executor for "+d.name); err != nil {
					return err
				}
			}
		}
		if d.kind == "input" {
			if err := add("graphql_normalize_input_"+d.name, "generated input normalizer for "+d.name); err != nil {
				return err
			}
			for _, f := range d.fields {
				if err := addNormalizerNames(add, "input_"+d.name+"_"+f.name, f.typ); err != nil {
					return err
				}
			}
		}
		for _, f := range d.fields {
			if d.kind == "type" && len(f.args) > 0 {
				if err := add(argsTypeName(d.name, f.name), d.name+"."+f.name+" arguments"); err != nil {
					return err
				}
			}
			if d.kind == "type" {
				if err := add(resolverName(d.name, f.name), "resolver for "+d.name+"."+f.name); err != nil {
					return err
				}
				if err := add("graphql_call_"+d.name+"_"+f.name, "generated wrapper for "+d.name+"."+f.name); err != nil {
					return err
				}
				for level := 0; ; level++ {
					generated := fmt.Sprintf("graphql_encode_%s_%s_%d", d.name, f.name, level)
					if err := add(generated, "generated encoder for "+d.name+"."+f.name); err != nil {
						return err
					}
					if !f.typ.list || level > 63 {
						break
					}
					f.typ = f.typ.inner
				}
				for _, arg := range f.args {
					if err := addNormalizerNames(add, "arg_"+d.name+"_"+f.name+"_"+arg.name, arg.typ); err != nil {
						return err
					}
				}
				if len(f.args) > 0 {
					if err := add("graphql_resolver_args_"+d.name+"_"+f.name, "generated argument decoder for "+d.name+"."+f.name); err != nil {
						return err
					}
				}
			}
		}
		for _, v := range d.values {
			if d.kind == "enum" {
				if err := validSlangIdentifier(v); err != nil {
					return fmt.Errorf("enum value %s.%s %w", d.name, v, err)
				}
			}
		}
	}
	return nil
}

func addNormalizerNames(add func(string, string) error, prefix string, typ *typeRef) error {
	for level := 0; ; level++ {
		if err := add(fmt.Sprintf("graphql_normalize_%s_%d", prefix, level), "generated input value normalizer"); err != nil {
			return err
		}
		if !typ.list || level > 63 {
			return nil
		}
		typ = typ.inner
	}
}
func argsTypeName(parent, field string) string { return parent + "_" + field + "_Args" }
func resolverName(parent, field string) string { return "resolve_" + parent + "_" + field }

func valueJSON(v *value) (string, error) {
	switch v.kind {
	case "string":
		return v.raw, nil
	case "int", "float", "true", "false", "null":
		return v.raw, nil
	case "enum":
		return fmt.Sprintf("%q", v.name), nil
	case "list":
		parts := make([]string, 0, len(v.items))
		for i := range v.items {
			part, err := valueJSON(&v.items[i])
			if err != nil {
				return "", err
			}
			parts = append(parts, part)
		}
		return "[" + strings.Join(parts, ",") + "]", nil
	case "object":
		parts := make([]string, 0, len(v.fields))
		for _, field := range v.fields {
			part, err := valueJSON(&field.value)
			if err != nil {
				return "", err
			}
			parts = append(parts, fmt.Sprintf("%q:%s", field.name, part))
		}
		return "{" + strings.Join(parts, ",") + "}", nil
	default:
		return "", fmt.Errorf("unsupported default-value kind %q", v.kind)
	}
}

func sortedNames(m map[string]int) []string {
	names := make([]string, 0, len(m))
	for name := range m {
		names = append(names, name)
	}
	sort.Strings(names)
	return names
}
